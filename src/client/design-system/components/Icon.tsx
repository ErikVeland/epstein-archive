export type IconName = keyof typeof icons;

export interface IconProps {
  name: IconName;
  size?: 'xs' | 'sm' | 'md' | 'lg' | 'xl';
  color?:
    | 'primary'
    | 'secondary'
    | 'success'
    | 'warning'
    | 'danger'
    | 'info'
    | 'white'
    | 'gray'
    | 'inherit'
    | 'black'
    | 'blue';
  className?: string;
  ariaLabel?: string;
  ariaHidden?: boolean;
}

const sizeClasses = {
  xs: 'h-3 w-3',
  sm: 'h-4 w-4',
  md: 'h-5 w-5',
  lg: 'h-6 w-6',
  xl: 'h-8 w-8',
} as const;

const colorClasses = {
  primary: 'text-[var(--accent)]',
  secondary: 'text-[var(--accent-secondary)]',
  success: 'text-[var(--accent-success)]',
  warning: 'text-[var(--accent-warning)]',
  danger: 'text-[var(--accent-danger)]',
  info: 'text-[var(--accent)]',
  white: 'text-[var(--text-primary)]',
  gray: 'text-[var(--text-muted)]',
  black: 'text-[var(--bg-dark)]',
  blue: 'text-[var(--accent)]',
  inherit: '',
} as const;

export const Icon: React.FC<IconProps> = ({
  name,
  size = 'md',
  color = 'white',
  className,
  ariaLabel,
  ariaHidden = false,
}) => {
  const IconComponent = icons[name];

  if (!IconComponent) {
    console.warn(`Icon "${name}" not found in design-system icon library`);
    return null;
  }

  return (
    <IconComponent
      className={cn(sizeClasses[size], colorClasses[color], 'shrink-0', className)}
      aria-label={ariaLabel}
      aria-hidden={ariaHidden}
    />
  );
};
